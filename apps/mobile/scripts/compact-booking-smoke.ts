import assert from 'node:assert/strict';
import type { Browser } from 'playwright';
import type { prisma as Prisma } from '../../api/src/db/client.js';
import { preferBookingTime, selectedBookingDate } from './booking-controls.utils';
export async function compactBookingSmoke({ browser, webUrl, prisma, run, businessIds }: { browser: Browser; webUrl: string; prisma: typeof Prisma; run: string; businessIds: string[] }) {
  const business = await prisma.business.create({ data: { name: `Compact ${run}`, slug: `compact-${run}`, timezone: 'Asia/Jerusalem', approvalStatus: 'APPROVED', publishedAt: new Date() } });
  businessIds.push(business.id);
  const service = await prisma.service.create({ data: { businessId: business.id, name: 'A deliberately long consultation service name for mobile wrapping', durationMinutes: 30, priceMinor: 12000, currency: 'ILS' } });
  const staff = await prisma.staff.create({ data: { businessId: business.id, displayName: 'Calendar specialist', parallelCapacity: 1 } });
  await prisma.staffService.create({ data: { businessId: business.id, serviceId: service.id, staffId: staff.id } });
  await prisma.bookingPolicy.create({ data: { businessId: business.id, minimumNoticeMinutes: 0, maximumAdvanceDays: 30, cancellationCutoffMinutes: 0, rescheduleCutoffMinutes: 0 } });
  await prisma.businessWeeklyAvailability.createMany({ data: Array.from({ length: 7 }, (_, weekday) => ({ businessId: business.id, weekday, startLocal: '09:00', endLocal: '17:00' })) });
  const date = new Date(Date.now() + 86400000).toISOString().slice(0, 10), next = new Date(Date.now() + 2 * 86400000).toISOString().slice(0, 10);
  await prisma.scheduleOverride.create({ data: { businessId: business.id, date: new Date(`${date}T00:00Z`), isOpen: false } });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, timezoneId: 'America/Los_Angeles' });
  try {
    const page = await context.newPage();
    await page.goto(`${webUrl}/booking/${business.id}?date=${date}`);
    await page.getByRole('heading', { name: 'תורים זמינים' }).waitFor();
    assert.equal(await page.locator('html').getAttribute('dir'), 'rtl');
    await page.getByTestId('booking-date-trigger').click();
    await page.getByTestId(`booking-day-${date}`).waitFor();
    assert.equal(await page.getByTestId(`booking-day-${date}`).isDisabled(), true);
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.getByTestId('booking-date-trigger').evaluate(node => node === document.activeElement), true);
    await page.goto(`${webUrl}/account`); await page.getByTestId('language-en').click();
    await page.goto(`${webUrl}/booking/${business.id}?date=${date}`);
    await page.getByRole('heading', { name: 'Available appointments' }).waitFor();
    await page.getByText('No available times on this date. Choose another date or look for the next available day.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Find the next available date', exact: true }).click();
    await page.getByRole('button', { name: /09:00 · Calendar specialist/ }).waitFor();
    assert.equal(await selectedBookingDate(page), next);
    assert.equal(await page.getByRole('button', { name: /Calendar specialist/ }).count(), 6);
    await preferBookingTime(page, '15:00');
    await page.getByRole('button', { name: /15:00 · Calendar specialist/ }).waitFor();
    await page.getByRole('button', { name: 'Earlier', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: /Calendar specialist/ }).count(), 6);
    await preferBookingTime(page, '25:00');
    await page.getByRole('alert').filter({ hasText: 'Enter a time' }).waitFor();
    assert.equal(await page.getByRole('button', { name: /Calendar specialist/ }).count(), 0);
    await preferBookingTime(page, '');
    let fail = true;
    await page.route('**/booking-calendar?*', async route => { if (fail) await route.fulfill({ status: 503, json: { error: 'Unavailable' } }); else await route.continue(); });
    await page.getByTestId('booking-date-trigger').click();
    await page.getByRole('alert').filter({ hasText: 'Available dates could not load.' }).waitFor();
    fail = false; await page.getByRole('dialog').getByRole('button', { name: 'Try again', exact: true }).click();
    await page.getByTestId(`booking-day-${next}`).waitFor();
    await page.getByTestId(`booking-day-${next}`).click();
    await page.setViewportSize({ width: 1280, height: 900 });
    assert.equal(await page.locator('html').getAttribute('dir'), 'ltr');
    const second = await prisma.service.create({ data: { businessId: business.id, name: 'Second consultation', durationMinutes: 45, priceMinor: 15000, currency: 'ILS' } });
    await page.reload();
    await page.getByRole('button', { name: /Choose a service/ }).click();
    await page.getByRole('dialog', { name: 'Choose a service', exact: true }).getByRole('button', { name: /Second consultation/ }).click();
    await page.getByText('No available times on this date. Choose another date or look for the next available day.', { exact: true }).waitFor();
    await prisma.service.updateMany({ where: { id: { in: [service.id, second.id] } }, data: { active: false } });
    await page.reload();
    await page.getByText('No services are available for booking.', { exact: true }).waitFor();
    assert.equal(await page.getByTestId('booking-date-trigger').isDisabled(), true);
    assert.equal(await prisma.booking.count({ where: { businessId: business.id } }), 0);
    console.log('PASS: compact sole-service auto-selection, Hebrew RTL calendar/Escape, closed dates, bounded next date, six-slot preference/paging, invalid time, calendar retry and advisory zero writes across traveler timezone/mobile/desktop.');
  } finally { await context.close(); }
}
